from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List


@dataclass
class SyntheticSample:
    """A synthetic code document with metadata."""

    doc_id: str
    language: str
    content: str
    license: str = "Apache-2.0"
    source: str = "synthetic-pipeline-generator-only"


def generate_synthetic_samples(count: int = 20) -> List[SyntheticSample]:
    """Generates synthetic code samples across Python, JavaScript, and Bash for pipeline testing."""
    samples: List[SyntheticSample] = []

    for i in range(count):
        # 1. Python sample
        py_code = f"""# Synthetic Python Sample {i} (For pipeline verification only)
def calculate_metric_{i}(values: list[float]) -> float:
    \"\"\"Calculates running statistics for index {i}.\"\"\"
    if not values:
        return 0.0
    total = sum(v * {i + 1} for v in values)
    return total / len(values)

class Runner_{i}:
    def __init__(self, name: str = "task_{i}"):
        self.name = name
        self.iteration = {i}

    def execute(self) -> dict:
        return {{"status": "ok", "iteration": self.iteration, "metric": calculate_metric_{i}([1.0, 2.5, 3.8])}}
"""
        samples.append(
            SyntheticSample(
                doc_id=f"synth_py_{i}",
                language="python",
                content=py_code,
            )
        )

        # 2. JavaScript / Web sample
        js_code = f"""// Synthetic JavaScript Sample {i}
async function fetchSystemStatus_{i}(endpointUrl) {{
    const response = await fetch(endpointUrl + "/api/v1/status/{i}");
    if (!response.ok) {{
        throw new Error(`HTTP error! status: ${{response.status}}`);
    }}
    const data = await response.json();
    console.log(`Received system data for node {i}:`, data);
    return data;
}}
export {{ fetchSystemStatus_{i} }};
"""
        samples.append(
            SyntheticSample(
                doc_id=f"synth_js_{i}",
                language="javascript",
                content=js_code,
            )
        )

        # 3. Bash sample
        sh_code = f"""#!/usr/bin/env bash
# Synthetic Shell Script {i}
set -euo pipefail
NODE_ID="{i}"
echo "Running system verification for node ${{NODE_ID}}..."
check_disk_space() {{
    local available
    available=$(df -h . | awk 'NR==2 {{print $4}}')
    echo "Available space: ${{available}}"
}}
check_disk_space
"""
        samples.append(
            SyntheticSample(
                doc_id=f"synth_sh_{i}",
                language="bash",
                content=sh_code,
            )
        )

    return samples
